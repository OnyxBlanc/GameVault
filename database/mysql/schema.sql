CREATE TABLE IF NOT EXISTS jeux (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source VARCHAR(64) NOT NULL,
  id_source VARCHAR(191) NOT NULL,
  titre VARCHAR(255) NOT NULL,
  date_sortie DATE,
  description TEXT,
  image_url TEXT,
  UNIQUE (source, id_source),
  KEY idx_jeux_titre (titre)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS genres (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nom VARCHAR(100) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jeu_genres (
  jeu_id BIGINT UNSIGNED NOT NULL,
  genre_id BIGINT UNSIGNED NOT NULL,
  PRIMARY KEY (jeu_id, genre_id),
  FOREIGN KEY (jeu_id) REFERENCES jeux(id),
  FOREIGN KEY (genre_id) REFERENCES genres(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS joueurs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  pseudo VARCHAR(32) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  credits BIGINT UNSIGNED NOT NULL DEFAULT 0,
  starter_claimed TINYINT(1) NOT NULL DEFAULT 0,
  cree_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS collections (
  joueur_id BIGINT UNSIGNED NOT NULL,
  jeu_id BIGINT UNSIGNED NOT NULL,
  quantite INT UNSIGNED NOT NULL DEFAULT 1 CHECK (quantite > 0),
  ajoute_le TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (joueur_id, jeu_id),
  FOREIGN KEY (joueur_id) REFERENCES joueurs(id),
  FOREIGN KEY (jeu_id) REFERENCES jeux(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
